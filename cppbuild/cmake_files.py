COMPILED_SUFFIXES = {".cpp", ".cc", ".cxx", ".c"}
# C++20 module interface units, built through a CXX_MODULES file set.
MODULE_SUFFIXES = {".ixx", ".cppm", ".mpp", ".ccm", ".cxxm"}
# Built on Windows too: resource scripts (icons, version information), manifests and
# module-definition files (DLL exports).
WINDOWS_COMPILED_SUFFIXES = {".rc", ".manifest", ".def"}
# Directory names the source scan never enters, here and in the generated CMake.
SCAN_EXCLUDED = (".cppbuild", ".git", "build", "__pycache__", ".cache", ".venv")
# The conventions between generated files (CPPBUILD_REQUEST_*, aliases, ...). A linked
# Solution's files must use the same one, e.g. when they come from another repository.
FORMAT = 2
# Same rules as git_sources.fetch(): clone a missing place at the recorded commit through a
# temporary directory; never change an existing place, only compare it with the record.
GIT_SOURCE_FUNCTION = r'''function(_cppbuild_git_source directory url revision solution)
  set(_place "${CMAKE_CURRENT_SOURCE_DIR}/${directory}")
  find_package(Git QUIET)
  if(EXISTS "${_place}/${solution}/project.json")
    if(GIT_EXECUTABLE AND EXISTS "${_place}/.git")
      execute_process(COMMAND "${GIT_EXECUTABLE}" -C "${_place}" rev-parse HEAD
        RESULT_VARIABLE _result OUTPUT_VARIABLE _head OUTPUT_STRIP_TRAILING_WHITESPACE ERROR_QUIET)
      if(_result EQUAL 0 AND NOT _head STREQUAL revision)
        message(WARNING "${directory} is at ${_head}, but ${revision} is recorded for ${url}; it is left unchanged")
      endif()
    endif()
    return()
  endif()
  if(EXISTS "${_place}")
    set(_reason "the place exists without ${solution}/project.json")
  elseif(NOT CPPBUILD_FETCH)
    set(_reason "CPPBUILD_FETCH is OFF")
  elseif(NOT GIT_EXECUTABLE)
    set(_reason "git was not found")
  else()
    set(_temporary "${_place}.cppbuild-fetch")
    file(REMOVE_RECURSE "${_temporary}")
    message(STATUS "CppBuild: cloning ${url} at ${revision} into ${directory}")
    execute_process(COMMAND "${GIT_EXECUTABLE}" clone --no-checkout -- "${url}" "${_temporary}"
      RESULT_VARIABLE _result OUTPUT_QUIET ERROR_VARIABLE _error)
    if(_result EQUAL 0)
      execute_process(COMMAND "${GIT_EXECUTABLE}" -c advice.detachedHead=false -C "${_temporary}" checkout --detach "${revision}"
        RESULT_VARIABLE _result OUTPUT_QUIET ERROR_VARIABLE _error)
    endif()
    if(_result EQUAL 0 AND EXISTS "${_temporary}/${solution}/project.json")
      file(RENAME "${_temporary}" "${_place}")
      return()
    endif()
    file(REMOVE_RECURSE "${_temporary}")
    if(_result EQUAL 0)
      set(_error "no CppBuild Solution at ${solution}")
    endif()
    string(STRIP "${_error}" _error)
    string(REPLACE "\n" " " _reason "git failed: ${_error}")
  endif()
  set_property(GLOBAL APPEND_STRING PROPERTY CPPBUILD_GIT_MISSING
    "\n  ${directory}: ${url} at ${revision} (${_reason})\n    git clone ${url} ${directory} && git -C ${directory} checkout ${revision}")
endfunction()'''
# The same files as CppBuild's source scan (engine._scan), collected again whenever the build
# runs: one glob per directory, so excluded directories are never entered and an added
# directory is noticed by its parent's glob. CMake lists cannot hold ";", which CppBuild rejects.
def _collect_function():
    # Two backslashes: CMake reads one of them as the escape of a quoted argument.
    excluded = "|".join(name.replace(".", "\\\\.") for name in SCAN_EXCLUDED)
    def pattern(suffixes):
        return "|".join("".join(f"[{c.lower()}{c.upper()}]" if c.isalpha() else c for c in suffix[1:])
                        for suffix in sorted(suffixes))
    compiled = pattern(COMPILED_SUFFIXES)
    modules = pattern(MODULE_SUFFIXES)
    windows = pattern(WINDOWS_COMPILED_SUFFIXES)
    marker = output_paths.MARKER
    return f"""function(_cppbuild_collect_sources result modules)
  set(_files)
  set(_pending)
  foreach(_root IN LISTS ARGN)
    set(_root "${{_cppbuild_project_dir}}/${{_root}}")
    # Also notices a source directory created later.
    file(GLOB _found CONFIGURE_DEPENDS LIST_DIRECTORIES true "${{_root}}")
    if(IS_DIRECTORY "${{_root}}" AND NOT EXISTS "${{_root}}/{marker}")
      list(APPEND _pending "${{_root}}")
    endif()
  endforeach()
  while(_pending)
    list(POP_FRONT _pending _directory)
    # Glob patterns treat [ * ? specially; [[] [*] [?] match them literally.
    string(REPLACE "[" "[[]" _pattern "${{_directory}}")
    string(REPLACE "*" "[*]" _pattern "${{_pattern}}")
    string(REPLACE "?" "[?]" _pattern "${{_pattern}}")
    file(GLOB _children CONFIGURE_DEPENDS LIST_DIRECTORIES true "${{_pattern}}/*")
    foreach(_child IN LISTS _children)
      get_filename_component(_name "${{_child}}" NAME)
      if(IS_SYMLINK "${{_child}}")
        # Symbolic links and junctions are skipped, as by the scan.
      elseif(IS_DIRECTORY "${{_child}}")
        if(NOT _name MATCHES "^({excluded})$" AND NOT EXISTS "${{_child}}/{marker}")
          list(APPEND _pending "${{_child}}")
        endif()
      elseif(_name STREQUAL "{ENTRY}" OR _name STREQUAL "{TOP_LEVEL}")
        file(STRINGS "${{_child}}" _first LIMIT_COUNT 1)
        if(NOT _first MATCHES "^{MARKER}")
          list(APPEND _files "${{_child}}")
        endif()
      else()
        list(APPEND _files "${{_child}}")
      endif()
    endforeach()
  endwhile()
  list(REMOVE_DUPLICATES _files)
  list(SORT _files)
  # Only these suffixes are built; other files are listed for the IDE.
  set(_built "{compiled}")
  if(WIN32)
    string(APPEND _built "|{windows}")
  endif()
  # Module interface units go to a file set instead of the plain sources.
  set(_modules ${{_files}})
  list(FILTER _modules INCLUDE REGEX "\\\\.({modules})$")
  list(FILTER _files EXCLUDE REGEX "\\\\.({modules})$")
  set(_display ${{_files}})
  list(FILTER _display EXCLUDE REGEX "\\\\.(${{_built}})$")
  if(_display)
    set_source_files_properties(${{_display}} PROPERTIES HEADER_FILE_ONLY TRUE)
  endif()
  set(${{result}} ${{_files}} PARENT_SCOPE)
  set(${{modules}} ${{_modules}} PARENT_SCOPE)
endfunction()"""


# C++20 module scanning costs a step per source file, so only targets that have module
# interface units, or link to a target that has them, are scanned. Runs once every target exists.
MODULE_SCANNING_FUNCTION = """function(_cppbuild_module_scanning)
  get_property(_modules GLOBAL PROPERTY CPPBUILD_MODULE_TARGETS)
  if(NOT _modules)
    return()
  endif()
  get_property(_targets GLOBAL PROPERTY CPPBUILD_COMPILED_TARGETS)
  foreach(_target IN LISTS _targets)
    set(_pending ${_target})
    set(_seen)
    while(_pending)
      list(POP_FRONT _pending _item)
      if(NOT TARGET "${_item}")
        continue()
      endif()
      get_target_property(_aliased "${_item}" ALIASED_TARGET)
      if(_aliased)
        set(_item "${_aliased}")
      endif()
      if(_item IN_LIST _seen)
        continue()
      endif()
      list(APPEND _seen "${_item}")
      if(_item IN_LIST _modules)
        set_property(TARGET ${_target} PROPERTY CXX_SCAN_FOR_MODULES ON)
        break()
      endif()
      get_target_property(_links "${_item}" LINK_LIBRARIES)
      get_target_property(_interface "${_item}" INTERFACE_LINK_LIBRARIES)
      foreach(_link IN LISTS _links _interface)
        if(_link AND NOT _link MATCHES "-NOTFOUND$")
          list(APPEND _pending "${_link}")
        endif()
      endforeach()
    endwhile()
  endforeach()
endfunction()"""


